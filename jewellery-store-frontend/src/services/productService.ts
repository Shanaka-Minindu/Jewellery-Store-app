import apiClient from '@/lib/axios';
import { ProductReqDto } from '@/types/product';



export const productService = {
  getPresignedUrl: async (fileName: string, fileType: string): Promise<string> => {
    const response = await apiClient.get<{ uploadUrl: string }>('/product/presigned-url', {
      params: { fileName, fileType },
    });
    return response.data.uploadUrl;
  },

  uploadFileToS3: async (file: File): Promise<string> => {
    // 1. Get pre-signed URL from Spring Boot
    const uploadUrl = await productService.getPresignedUrl(file.name, file.type);

    // 2. Upload file binary directly to AWS S3 using PUT request
    await apiClient.put(uploadUrl, file, {
      headers: {
        'Content-Type': file.type,
      },
      // Bypass standard interceptors for direct S3 upload if baseURL interferes
      baseURL: undefined, 
    });

    // 3. Return public clean S3 file URL (stripping query parameters generated by pre-signing)
    const cleanUrl = uploadUrl.split('?')[0];
    return cleanUrl;
  },

  createProduct: async (data: ProductReqDto): Promise<{ id: number; message: string }> => {
    console.log(data)
    const response = await apiClient.post('/product', data);
    return response.data;
  },
};